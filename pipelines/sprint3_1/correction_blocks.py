    text = FINAL.read_text(encoding="utf-8")
    new = apply(text)
    FINAL.write_text(new, encoding="utf-8")
    missing = [a for a, _ in INLINE if a not in text]
    print(f"correction blocks: {new.count(MARK)} (summary + {len(INLINE) - len(missing)} inline); "
          f"anchors not found: {missing}")
    return 1 if missing else 0


