def apply(text: str) -> str:
    if MARK in text:
        return text  # idempotent
    lines = text.split("\n")
    out: list[str] = []
    header_done = False
    for i, line in enumerate(lines):
        out.append(line)
        if not header_done and line.startswith("*Generated by"):
            out += ["", SUMMARY]
            header_done = True
            continue
        for anchor, body in INLINE:
            if line.startswith(anchor):
                out += ["", f"> **{MARK}).** {body}"]
                break
    return "\n".join(out)


