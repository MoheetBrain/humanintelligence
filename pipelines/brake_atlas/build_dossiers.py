# ----------------------------------------------------------------------- helpers
def load_claim_ids() -> set[str]:
    ids: set[str] = set()
    for path in sorted(CLAIMS_DIR.glob("*.yaml")):
        for claim in yaml.safe_load(path.read_text(encoding="utf-8")) or []:
            ids.add(claim["claim_id"])
    return ids


def collect_refs(spec: dict) -> set[str]:
    refs = set(spec.get("mechanism_chain") or [])
    for sv in spec.get("state_variables") or []:
        refs |= set(sv.get("claim_refs") or [])
    for facet in spec["facets"].values():
        refs |= set(facet.get("claim_refs") or [])
        refs |= set(facet.get("counter_claim_refs") or [])
    return refs


