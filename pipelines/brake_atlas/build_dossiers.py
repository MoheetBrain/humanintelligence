def validate(known: set[str]) -> list[str]:
    errors: list[str] = []
    for symbol, spec in TARGETS.items():
        for ref in sorted(collect_refs(spec)):
            if ref not in known:
                errors.append(f"{symbol}: references unknown claim {ref}")
        for name in OWNED_FACETS:
            if name not in spec["facets"]:
                errors.append(f"{symbol}: missing owned facet {name}")
                continue
            f = spec["facets"][name]
            status = f.get("assessment_status", "assessed")
            if status == "assessed":
                if f.get("level") not in (0, 1, 2, 3, 4):
                    errors.append(f"{symbol}.{name}: level {f.get('level')!r} not in 0..4")
                if f.get("counter_level") not in (0, 1, 2, 3, 4):
                    errors.append(f"{symbol}.{name}: counter_level {f.get('counter_level')!r} not in 0..4")
                if not f.get("claim_refs") and f.get("level", 0) > 0:
                    errors.append(f"{symbol}.{name}: level > 0 with no claim_refs")
                if f.get("level") == 0 and (symbol, name) not in SEARCH_BASIS:
                    errors.append(f"{symbol}.{name}: level 0 with no search_basis (R11)")
                if not f.get("counter_claim_refs") and (f.get("counter_level") or 0) > 0:
                    errors.append(f"{symbol}.{name}: counter_level > 0 with no counter_claim_refs")
            else:
                if f.get("level") is not None or f.get("counter_level") is not None:
                    errors.append(f"{symbol}.{name}: not_assessed must carry null levels")
            # A human-proposition facet may not reach level 3+ without human evidence.
            if name == "human_intervention_evidence" and (f.get("level") or 0) >= 3 and not f.get("claim_refs"):
                errors.append(f"{symbol}.{name}: level >= 3 with no cited human claims")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate without writing")
    args = parser.parse_args(argv)

    known = load_claim_ids()
    errors = validate(known)
    if errors:
        for e in errors:
            print(f"ERROR {e}", file=sys.stderr)
        return 1
    print(f"validated {len(TARGETS)} targets against {len(known)} registered claims")
    if args.check:
        return 0

    DOSSIER_DIR.mkdir(parents=True, exist_ok=True)
    ASSESS_DIR.mkdir(parents=True, exist_ok=True)
    for symbol, spec in TARGETS.items():
        dpath = DOSSIER_DIR / f"{symbol}.yaml"
        apath = ASSESS_DIR / f"{symbol}.yaml"
        dpath.write_text(
            HEADER.format(kind="Target dossier", symbol=symbol, section="section 5.1")
            + yaml.safe_dump(dossier_doc(symbol, spec), sort_keys=False, allow_unicode=True, width=100),
            encoding="utf-8",
        )
        apath.write_text(
            HEADER.format(kind="Facet assessment", symbol=symbol, section="section 5.2")
            + yaml.safe_dump(assessment_doc(symbol, spec), sort_keys=False, allow_unicode=True, width=100),
            encoding="utf-8",
        )
    print(f"wrote {len(TARGETS)} dossiers to {DOSSIER_DIR} and {len(TARGETS)} assessments to {ASSESS_DIR}")
    return 0


